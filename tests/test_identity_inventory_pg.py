def test_current_tapdb_inventory_contains_only_owner_minted_euids(pg_instance):
    runner = CliRunner()
    config = str(pg_instance["config_path"])
    result = runner.invoke(app, ["--config", config, "db", "schema", "apply"])
    assert result.exit_code == 0, result.output
    result = runner.invoke(
        app, ["--config", config, "db", "data", "seed", "--skip-existing"]
    )
    assert result.exit_code == 0, result.output
    engine = create_engine(
        pg_instance["operator_dsn"],
        poolclass=NullPool,
        isolation_level="REPEATABLE READ",
    )
    target = {
        "engine_type": "local",
        "host": "localhost",
        "port": pg_instance["port"],
        "database": pg_instance["database"],
        "schema_name": pg_instance["schema_name"],
        "config_identity": config,
        "domain_code": "Z",
        "owner_repo_name": "daylily-tapdb",
    }
    try:
        with engine.begin() as connection:
            evidence = capture(connection, target)
            templates = evidence["tables"]["generic_template"]["rows"]
            # The session-scoped database may contain other tests' legitimate
            # templates; every persisted row must still be inventoried.
            assert (
                templates
                and len(templates)
                == connection.execute(
                    text(
                        f'SELECT count(*) FROM "{target["schema_name"]}".generic_template'
                    )
                ).scalar_one()
            )
            for row in templates.values():
                identity = row["identity"]
                persisted = connection.execute(
                    text(
                        f'SELECT euid FROM "{target["schema_name"]}".generic_template WHERE uid=:uid'
                    ),
                    {"uid": identity["uid"]},
                ).scalar_one()
                assert identity["euid"] == persisted
    finally:
        engine.dispose()


def test_constrained_schema_owner_complete_force_rls_capture(historical, pg_instance):
    engine, target = historical
    schema = target["schema_name"]
    owner = "inventory_owner_" + uuid4().hex
    with engine.begin() as connection:
        connection.execute(text(f'CREATE ROLE "{owner}" LOGIN NOSUPERUSER NOBYPASSRLS'))
        connection.execute(
            text(f'GRANT CONNECT ON DATABASE "{target["database"]}" TO "{owner}"')
        )
        connection.execute(text(f'ALTER SCHEMA "{schema}" OWNER TO "{owner}"'))
        connection.execute(
            text(f'ALTER TABLE "{schema}".original_history OWNER TO "{owner}"')
        )
        connection.execute(
            text(f'ALTER TABLE "{schema}".unkeyed_history OWNER TO "{owner}"')
        )
        connection.execute(
            text(f'ALTER TABLE "{schema}".original_history ENABLE ROW LEVEL SECURITY')
        )
        connection.execute(
            text(f'ALTER TABLE "{schema}".original_history FORCE ROW LEVEL SECURITY')
        )
        connection.execute(
            text(
                f'CREATE POLICY tapdb_operator_access ON "{schema}".original_history FOR ALL TO "{owner}" USING (true) WITH CHECK (true)'
            )
        )
        expected = capture(connection, target)
    owner_engine = create_engine(
        engine.url.set(username=owner),
        poolclass=NullPool,
        isolation_level="REPEATABLE READ",
    )
    try:
        with owner_engine.begin() as connection:
            connection.execute(text("SET TRANSACTION READ ONLY"))
            actual = capture(connection, target)
            assert actual == expected
            assert actual["tables"]["original_history"]["row_count"] == 2
        with engine.begin() as connection:
            connection.execute(
                text(
                    f'CREATE POLICY hidden_deleted ON "{schema}".original_history AS RESTRICTIVE FOR SELECT TO "{owner}" USING (NOT is_deleted)'
                )
            )
        with (
            owner_engine.begin() as connection,
            pytest.raises(DBAPIError, match="complete FORCE-RLS"),
        ):
            capture(connection, target)
    finally:
        owner_engine.dispose()
        with engine.begin() as connection:
            connection.execute(
                text(f'DROP POLICY hidden_deleted ON "{schema}".original_history')
            )
            connection.execute(
                text(
                    f'DROP POLICY tapdb_operator_access ON "{schema}".original_history'
                )
            )
            connection.execute(
                text(
                    f'ALTER TABLE "{schema}".original_history OWNER TO "{pg_instance["operator_user"]}"'
                )
            )
            connection.execute(
                text(
                    f'ALTER TABLE "{schema}".unkeyed_history OWNER TO "{pg_instance["operator_user"]}"'
                )
            )
            connection.execute(
                text(
                    f'ALTER SCHEMA "{schema}" OWNER TO "{pg_instance["operator_user"]}"'
                )
            )
            connection.execute(
                text(
                    f'REVOKE CONNECT ON DATABASE "{target["database"]}" FROM "{owner}"'
                )
            )
            connection.execute(text(f'DROP ROLE "{owner}"'))


def test_capture_is_stable_across_timezone_and_search_path(historical):
    engine, target = historical
    with engine.begin() as connection:
        connection.execute(text("SET LOCAL TimeZone = 'America/New_York'"))
        connection.execute(
            text(f'SET LOCAL search_path = "{target["schema_name"]}", public')
        )
        first = capture(connection, target)
        assert (
            connection.execute(text("SELECT current_schema()")).scalar_one()
            == target["schema_name"]
        )
    with engine.begin() as connection:
        connection.execute(text("SET LOCAL TimeZone = 'Asia/Tokyo'"))
        connection.execute(text("SET LOCAL search_path = pg_catalog"))
        second = capture(connection, target)
    assert first == second
