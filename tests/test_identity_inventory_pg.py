@pytest.fixture
def historical(pg_instance):
    schema = "historical_" + uuid4().hex
    engine = create_engine(
        pg_instance["operator_dsn"],
        poolclass=NullPool,
        isolation_level="REPEATABLE READ",
    )
    target = {
        "engine_type": "local",
        "host": "localhost",
        "port": pg_instance["port"],
        "database": pg_instance["database"],
        "schema_name": schema,
        "config_identity": str(pg_instance["config_path"]),
        "domain_code": "Z",
        "owner_repo_name": "daylily-tapdb",
    }
    with engine.begin() as connection:
        connection.execute(text(f'CREATE SCHEMA "{schema}"'))
        connection.execute(
            text(
                f'CREATE TABLE "{schema}".original_history (uid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_uid bigint REFERENCES "{schema}".original_history(uid), created_at timestamptz NOT NULL, note text, is_deleted boolean NOT NULL)'
            )
        )
        connection.execute(
            text(
                f"INSERT INTO \"{schema}\".original_history(created_at,note,is_deleted) VALUES ('2026-09-10T20:00:00Z','kept',false),('2026-09-10T20:00:01Z','deleted-but-preserved',true)"
            )
        )
        connection.execute(text(f'CREATE TABLE "{schema}".unkeyed_history(note text)'))
        connection.execute(
            text(f"INSERT INTO \"{schema}\".unkeyed_history VALUES ('same'),('same')")
        )
        # Neither table appears in the previous fixed TapDB inventory.
    yield engine, target
    with engine.begin() as connection:
        connection.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
    engine.dispose()


def capture(connection, target):
    return capture_identity_inventory(
        connection, schema_name=target["schema_name"], target=target
    )


def test_historical_capture_needs_no_tapdb_runtime_schema(historical):
    engine, target = historical
    with engine.begin() as connection:
        before = capture(connection, target)
        after = capture(connection, target)
    assert before == after
    assert set(before["tables"]) == {"original_history", "unkeyed_history"}
    history = before["tables"]["original_history"]
    assert history["row_count"] == 2
    assert {"uid", "parent_uid", "created_at"} <= set(history["immutable_columns"])
    assert len(history["constraints"]) == 2 and history["dependencies"]
    reference = next(item for item in history["constraints"] if item["kind"] == "f")
    assert reference["referenced_schema"] == target["schema_name"]
    assert reference["referenced_table"] == "original_history"
    assert reference["referenced_columns"] == ["uid"]
    assert reference["validated"] is True
    assert before["tables"]["unkeyed_history"]["rows"]
    assert (
        next(iter(before["tables"]["unkeyed_history"]["rows"].values()))["count"] == 2
    )
    assert verify_identity_inventory(before, after)["ok"]
    assert "deleted-but-preserved" not in inventory_module.canonical_json(before)


def test_removed_history_duplicate_and_unknown_table_changes_are_detected(historical):
    engine, target = historical
    with engine.begin() as connection:
        before = capture(connection, target)
        connection.execute(
            text(
                f'DELETE FROM "{target["schema_name"]}".unkeyed_history WHERE ctid IN (SELECT ctid FROM "{target["schema_name"]}".unkeyed_history LIMIT 1)'
            )
        )
        after = capture(connection, target)
        assert not verify_identity_inventory(before, after)["ok"]
        connection.execute(
            text(
                f'CREATE TABLE "{target["schema_name"]}".new_history (uid bigint PRIMARY KEY)'
            )
        )
        latest = capture(connection, target)
    assert (
        "new_history:undeclared_table_added"
        in verify_identity_inventory(after, latest)["violations"]
    )


def test_capture_requires_snapshot_and_exact_physical_target(historical):
    engine, target = historical
    with engine.connect().execution_options(
        isolation_level="READ COMMITTED"
    ) as connection:
        with (
            connection.begin(),
            pytest.raises(IdentityInventoryError, match="REPEATABLE READ"),
        ):
            capture(connection, target)
    with engine.begin() as connection:
        with pytest.raises(IdentityInventoryError, match="physical target"):
            capture(connection, dict(target, database="wrong_target"))
    with engine.begin() as connection:
        with pytest.raises(IdentityInventoryError, match="Schema does not exist"):
            capture(connection, dict(target, schema_name="not_present"))


def test_read_only_capture_rejects_incomplete_forced_rls_visibility(
    historical, pg_instance
):
    engine, target = historical
    schema = target["schema_name"]
    runtime = pg_instance["user"]
    with engine.begin() as connection:
        connection.execute(
            text(f'ALTER TABLE "{schema}".original_history ENABLE ROW LEVEL SECURITY')
        )
        connection.execute(
            text(f'ALTER TABLE "{schema}".original_history FORCE ROW LEVEL SECURITY')
        )
        connection.execute(
            text(
                f'CREATE POLICY partial ON "{schema}".original_history USING (NOT is_deleted)'
            )
        )
        connection.execute(text(f'GRANT USAGE ON SCHEMA "{schema}" TO "{runtime}"'))
        connection.execute(
            text(f'GRANT SELECT ON ALL TABLES IN SCHEMA "{schema}" TO "{runtime}"')
        )
    runtime_engine = create_engine(
        pg_instance["dsn"], poolclass=NullPool, isolation_level="REPEATABLE READ"
    )
    try:
        with (
            runtime_engine.begin() as connection,
            pytest.raises(DBAPIError, match="complete FORCE-RLS"),
        ):
            capture(connection, target)
    finally:
        runtime_engine.dispose()
    with engine.begin() as connection:
        full = capture(connection, target)
        assert full["tables"]["original_history"]["row_count"] == 2
        assert full["tables"]["original_history"]["rls_forced"]


