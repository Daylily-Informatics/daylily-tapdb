def capture(connection, target):
    return capture_sequence_inventory(
        connection, schema_name=target["schema_name"], target=target
    )


def fence(current):
    return {
        "mode": "exclusive_database_connect",
        "database_oid": current["physical_target"]["database_oid"],
        "operator_role": "tapdb_operator",
    }


