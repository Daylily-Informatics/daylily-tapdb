def test_strong_gate_lifecycle_retains_session_through_verified_commit(
    allocator, control_connection, tmp_path
):
    from daylily_tapdb.sequences import (
        acquire_database_writer_fence,
        release_database_writer_fence,
    )

    engine, target = allocator
    extra_admin = "fixture_admin_" + uuid4().hex
    with engine.connect() as connection:
        with connection.begin():
            connection.execute(text(f'CREATE ROLE "{extra_admin}" LOGIN SUPERUSER'))
            current = capture(connection, target)
            with pytest.raises(SequenceProtectionError, match="CONNECT"):
                validate_writer_fence(connection, current, fence(current))
            plan = build_sequence_advance_plan(
                current,
                floors=[{"name": "objects_uid_seq", "value": 9, "source": "original"}],
            )
        try:
            with pytest.raises(SequenceProtectionError, match="unknown privileged"):
                acquire_database_writer_fence(
                    connection,
                    control_connection=control_connection,
                    inventory=current,
                    receipts_dir=tmp_path,
                )
        finally:
            with connection.begin():
                connection.execute(text(f'DROP ROLE "{extra_admin}"'))
        acquired = acquire_database_writer_fence(
            connection,
            control_connection=control_connection,
            inventory=current,
            receipts_dir=tmp_path,
        )
        try:
            with connection.begin():
                assert (
                    connection.execute(
                        text(
                            "SELECT datallowconn FROM pg_database WHERE datname=current_database()"
                        )
                    ).scalar_one()
                    is False
                )
                applied = apply_sequence_advance_plan(
                    connection,
                    plan,
                    writer_fence=acquired["fence"],
                    receipts_dir=tmp_path,
                )
            committed = record_sequence_advance_outcome(
                applied,
                receipts_dir=tmp_path,
                outcome="committed",
                actor="tapdb_operator",
            )
            released = release_database_writer_fence(
                connection,
                acquired,
                result=committed,
                receipts_dir=tmp_path,
                control_connection=control_connection,
            )
            assert released["phase"] == "released"
            assert released["fence_sha256"] == acquired["sha256"]
        finally:
            with connection.begin():
                connection.execute(
                    text(
                        f'ALTER DATABASE "{target["database"]}" ALLOW_CONNECTIONS true'
                    )
                )
    receipts = read_receipts(tmp_path)
    assert verify_receipt_chain(receipts, head=read_head(tmp_path)).ok
    assert [item.detail["phase"] for item in receipts] == [
        "acquire_intent",
        "acquired",
        "intent",
        "applied_pending_commit",
        "committed",
        "release_intent",
        "released",
    ]


