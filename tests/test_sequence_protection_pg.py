def test_cached_old_sessions_block_advance_until_closed(allocator, tmp_path):
    engine, target = allocator
    schema = target["schema_name"]
    with engine.begin() as connection:
        connection.execute(text(f'ALTER SEQUENCE "{schema}".objects_uid_seq CACHE 4'))
    other = engine.connect()
    assert (
        other.execute(
            text(f"SELECT nextval('\"{schema}\".objects_uid_seq')")
        ).scalar_one()
        == 8
    )
    other.commit()
    with engine.begin() as connection:
        before = capture(connection, target)
        assert before["sequences"][0]["last_value"] == 17
        with pytest.raises(SequenceProtectionError, match="sessions"):
            apply_sequence_advance_plan(
                connection,
                build_sequence_advance_plan(before, floors=[]),
                writer_fence=fence(before),
                receipts_dir=tmp_path,
            )
    other.close()
    with engine.begin() as connection:
        before = capture(connection, target)
        result = apply_sequence_advance_plan(
            connection,
            build_sequence_advance_plan(before, floors=[]),
            writer_fence=fence(before),
            receipts_dir=tmp_path,
        )
        assert sequence_next_value(result["inventory"]["sequences"][0]) == 20


