def test_rollback_keeps_external_floors_and_refuses_same_plan_retry(
    allocator, tmp_path
):
    engine, target = allocator
    with engine.connect() as connection:
        transaction = connection.begin()
        before = capture(connection, target)
        plan = build_sequence_advance_plan(
            before,
            floors=[{"name": "objects_uid_seq", "value": 20, "source": "reservation"}],
        )
        pending = apply_sequence_advance_plan(
            connection, plan, writer_fence=fence(before), receipts_dir=tmp_path
        )
        transaction.rollback()
    with engine.begin() as connection:
        assert capture(connection, target) == before
        with pytest.raises(SequenceProtectionError, match="already attempted"):
            apply_sequence_advance_plan(
                connection, plan, writer_fence=fence(before), receipts_dir=tmp_path
            )
    assert read_receipts(tmp_path)[0].detail["floors"][-1]["value"] == 23
    with engine.begin() as connection:
        current = capture(connection, target)
        insufficient = build_sequence_advance_plan(current, floors=[])
        with pytest.raises(SequenceProtectionError, match="previous attempt"):
            apply_sequence_advance_plan(
                connection,
                insufficient,
                writer_fence=fence(current),
                receipts_dir=tmp_path,
            )
    with engine.begin() as connection:
        current = capture(connection, target)
        retained = read_receipts(tmp_path)[0].detail["floors"]
        recovery = build_sequence_advance_plan(current, floors=retained)
        with pytest.raises(SequenceProtectionError, match="Unresolved prior allocator"):
            apply_sequence_advance_plan(
                connection, recovery, writer_fence=fence(current), receipts_dir=tmp_path
            )
        record_sequence_advance_outcome(
            pending, receipts_dir=tmp_path, outcome="ambiguous", actor="tapdb_operator"
        )
        with pytest.raises(SequenceProtectionError, match="Unresolved prior allocator"):
            apply_sequence_advance_plan(
                connection, recovery, writer_fence=fence(current), receipts_dir=tmp_path
            )
        # The retained caller observed rollback; a new process cannot invent this.
        record_sequence_advance_outcome(
            pending,
            receipts_dir=tmp_path,
            outcome="rolled_back",
            actor="tapdb_operator",
        )
        applied = apply_sequence_advance_plan(
            connection, recovery, writer_fence=fence(current), receipts_dir=tmp_path
        )
        assert sequence_next_value(applied["inventory"]["sequences"][0]) == 26


